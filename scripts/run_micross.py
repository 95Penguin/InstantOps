#!/usr/bin/env python3
"""Run MicroSS v2 preprocessing, temporal graph extraction, training and RCA."""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from data.config import (
    MICROSS_OUTPUT_DIR,
    MICROSS_PROCESSED_DIR,
    MICROSS_RAW_DIR,
    MICROSS_WORK_DIR,
    resolve_micross_root,
)


def pipeline_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "micross_root",
        type=Path,
        nargs="?",
        default=MICROSS_RAW_DIR,
        help="MicroSS directory (default: <project>/data/MicroSS)",
    )
    parser.add_argument("--data-dir", type=Path, default=MICROSS_PROCESSED_DIR)
    parser.add_argument("--output-dir", type=Path, default=MICROSS_OUTPUT_DIR)
    parser.add_argument("--work-dir", type=Path, default=MICROSS_WORK_DIR)
    parser.add_argument("--epochs", type=int, default=20)
    parser.add_argument("--history", type=int, default=5)
    parser.add_argument("--batch-size", type=int, default=128)
    parser.add_argument("--device", choices=("auto", "cpu", "cuda", "mps"), default="auto")
    parser.add_argument("--check-inputs-only", action="store_true")
    parser.add_argument("--skip-prepare", action="store_true")
    parser.add_argument("--skip-graph", action="store_true")
    parser.add_argument("--labels", type=Path, help="Label CSV generated by label_micross.py")
    parser.add_argument("--source-timezone", default="UTC")
    args = parser.parse_args()
    if min(args.epochs, args.history, args.batch_size) < 1:
        parser.error("epochs, history and batch-size must be positive")
    return args


def pipeline_main() -> int:
    args = pipeline_args()
    root = resolve_micross_root(args.micross_root)
    data = args.data_dir.expanduser().resolve()

    def run(script, *arguments):
        command = [sys.executable, str(Path(__file__).resolve()), {"prepare_micross.py": "prepare", "build_micross_graph.py": "graph", "train_micross.py": "train"}[script], *map(str, arguments)]
        print("Running:", " ".join(command), flush=True)
        subprocess.run(command, check=True, cwd=ROOT)

    if args.check_inputs_only:
        run("prepare_micross.py", root, "--check-inputs-only",
            "--source-timezone", args.source_timezone)
        return 0
    if not args.skip_prepare:
        run("prepare_micross.py", root, "--output", data, "--source-timezone", args.source_timezone)
    schema = json.loads((data / "feature_schema.json").read_text())
    if schema.get("source_timezone", "UTC") != args.source_timezone:
        raise ValueError("source timezone differs from cached data; regenerate preprocessing")
    if schema.get("version") != 2:
        raise ValueError("pipeline requires v2 data; regenerate preprocessing outputs")
    if not args.skip_graph:
        run(
            "build_micross_graph.py",
            root / "trace/trace_split.zip",
            "--training-data-dir",
            data,
            "--output-dir",
            data,
            "--history",
            args.history,
            "--work-dir",
            args.work_dir,
        )
    run(
        "train_micross.py",
        "--data-dir",
        data,
        "--graph",
        data / "service_adjacency_1m.npz",
        "--output-dir",
        args.output_dir,
        "--epochs",
        args.epochs,
        "--history",
        args.history,
        "--batch-size",
        args.batch_size,
        "--device",
        args.device,
        "--rca-method",
        "masking",
        *(["--labels", args.labels.resolve()] if args.labels else []),
    )
    return 0



